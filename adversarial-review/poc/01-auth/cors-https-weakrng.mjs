// §6/§8: CORS policy, missing HTTPS redirect, and non-crypto RNG for the code.
import { execFileSync } from 'node:child_process'
const BASE = 'http://localhost:5080'

// --- CORS: dev policy only allows http://localhost:5173. Probe with a hostile Origin. ---
async function probeOrigin(origin) {
  const res = await fetch(`${BASE}/api/auth/login`, {
    method: 'OPTIONS',
    headers: { 'Origin': origin, 'Access-Control-Request-Method': 'POST', 'Access-Control-Request-Headers': 'content-type' },
  })
  return res.headers.get('access-control-allow-origin')
}
const allowedForEvil = await probeOrigin('http://evil.example')
const allowedForDev = await probeOrigin('http://localhost:5173')
console.log(`[cors] Origin http://evil.example -> ACAO = ${allowedForEvil ?? '(none)'}`)
console.log(`[cors] Origin http://localhost:5173 -> ACAO = ${allowedForDev ?? '(none)'}`)
console.log(allowedForEvil ? `[cors] NOTE: evil origin reflected` : `[cors] REFUTED for wildcard: only the dev origin is allowed (good), but policy is hardcoded to localhost:5173 and AllowedHosts="*" in appsettings.`)

// --- HTTPS: Program.cs has no UseHttpsRedirection; plain HTTP serves the API. ---
const health = await fetch(`${BASE}/swagger/index.html`)
console.log(`[https] plain HTTP http://localhost:5080 served API (status ${health.status}); no UseHttpsRedirection in Program.cs -> token+password travel in cleartext.`)

// --- RNG: codes come from Random.Shared.Next (non-crypto). Show low entropy / sampling. ---
const sql = (q) => execFileSync('docker', ['exec', 'planner-mysql', 'mysql', '-N', '-uplanner', '-pplanner_dev_password', 'planner', '-e', q], { encoding: 'utf8' }).trim()
const codes = sql(`SELECT Code FROM EmailVerificationCodes ORDER BY Id DESC LIMIT 10;`).split(/\s+/).filter(Boolean)
console.log(`[rng] last codes in DB: ${codes.join(', ')} — generated by Random.Shared.Next(0,1e6) (AuthController.cs:53), NOT RandomNumberGenerator. ~20 bits, predictable given the seed/samples.`)
